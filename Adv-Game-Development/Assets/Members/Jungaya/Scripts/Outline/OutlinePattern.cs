namespace Toufuku.Rescue.Outline
{
    /*
        輪郭の線のもよう（#59）。色がわかりにくい人でも、もようだけでお守りの種類がわかるようにする

        企画書 v8 6章「5色とパターン」の表どおり。ボタン箱の天面に白で印刷するもようと同じにする:
          健康=実線 / 学業成就=点線 / 厄除け安全=破線 / 縁結び=波線 / 金運=二重線
        お守りの種類からもようを引くのは OutlineStyle.PatternFor

        この数字はマスクRT にはのせない（マスクには客の番号だけを入れて、もようは配列で Compose に渡す）
        シリアライズされるので、数字を変えるときは OutlineTarget を持っているプレハブやシーンも直すこと
    */
    public enum OutlinePattern
    {
        // 実線（健康）
        Solid = 0,
        // 点線（学業成就）。丸い点をならべる
        Dotted = 1,
        // 破線（厄除け安全）。長い線をすきまをあけてならべる
        Dashed = 2,
        // 波線（縁結び）
        Wavy = 3,
        // 二重線（金運）。細い線を2本ならべる
        Double = 4,
    }
}
