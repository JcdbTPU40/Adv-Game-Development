namespace Toufuku.Rescue
{
    /*
        客の「種類」（企画書 v8 付録B B-1）（#54）

        CustomerType（＝なやみの種類＝ほしいお守りの色）とは別のもの
        こっちは「何発で救えるか、どれくらいで危険度Dが100になるか、救ったときの基礎点」を決める
          ・色（CustomerType）: 輪郭が光る色と、相性の判定に使う
          ・種類（CustomerKind）: 最初のR・D が満タンになる秒数・基礎点・評価の増減に使う

        数値は CustomerKindTable（付録B B-1 を写したもの）が正しい。enum は名前だけを持つ
    */
    public enum CustomerKind
    {
        // 通常客: 最初のR=1 / D満タン15〜25秒 / 基礎点100
        Normal,
        // 移動客: 最初のR=1 / D満タン20秒 / 基礎点150。active のまま横に動く
        Moving,
        // 遠方客: 最初のR=1 / D満タン22秒 / 基礎点200
        Distant,
        // 欲張り客: 最初のR=2 / D満タン28秒 / 基礎点300。とちゅうの点はない（R=0 で救えたときだけ点が入る）
        Greedy,
        // ボス客: 最初のR=3 / D満タン30秒 / 基礎点500。頭の上のゲージは3つに区切った目もり
        Boss
    }
}
