namespace Toufuku.Rescue
{
    /*
        お守りの種類（ボタン5個に対応）。企画書 v3 §3 で決まった
          名前が変わったらここを1か所直すだけですむように、enum にまとめておく

        ※ この enum の順番＝ボタン箱の実際のならび順（左から右）
          変えるときはハードのほうのならびもいっしょに変えること（v3 §3: 5つのボタンの色は
          お守り5種の色・輪郭の光・弾の色と完全にそろえる）
        ※ 値は int としてアセットに保存されるので、ならべかえたり足したりするときは
          保存ずみのデータ（.asset / .prefab / .unity ファイル）を直す必要がある
    */
    public enum OmamoriType
    {
        Kenkou,   // 健康
        Gakugyou, // 学業成就
        Yakuyoke, // 厄除け安全
        Enmusubi, // 縁結び
        Kinun     // 金運
    }

    // 相性の判定の結果。救済の判定（#13）はこの2つだけを受け取って動く
    public enum Affinity
    {
        Good, // 相性◯（正しいお守り）→ ゲージを大きく減らす
        Bad   // 相性✗（まちがい）→ ゲージを少しだけ減らす＋コンボが切れる
    }
}
